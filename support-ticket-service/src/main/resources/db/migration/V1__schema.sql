CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE, site VARCHAR(80) NOT NULL, area VARCHAR(80) NOT NULL,
  status VARCHAR(15) NOT NULL, password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) NOT NULL
);
CREATE TABLE technicians (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL, salary DECIMAL(12,2) NOT NULL,
  affiliation_date DATE NOT NULL, status VARCHAR(15) NOT NULL, specialty VARCHAR(20) NOT NULL
);
CREATE TABLE tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, requester_id BIGINT NOT NULL, technician_id BIGINT,
  title VARCHAR(140) NOT NULL, description VARCHAR(2000) NOT NULL, category VARCHAR(20) NOT NULL,
  priority VARCHAR(20) NOT NULL, site VARCHAR(80) NOT NULL, affected_asset VARCHAR(120) NOT NULL,
  status VARCHAR(20) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL, sla_due_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_ticket_requester FOREIGN KEY (requester_id) REFERENCES users(id),
  CONSTRAINT fk_ticket_technician FOREIGN KEY (technician_id) REFERENCES technicians(id)
);
CREATE TABLE ticket_histories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL,
  previous_status VARCHAR(20), new_status VARCHAR(20) NOT NULL, observation VARCHAR(1000) NOT NULL,
  changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_history_ticket FOREIGN KEY (ticket_id) REFERENCES tickets(id)
);
